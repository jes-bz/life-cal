import assert from 'node:assert/strict';
import { build } from 'esbuild';
const built = await build({absWorkingDir: new URL('../', import.meta.url).pathname,entryPoints:['src/index.ts'],bundle:true,write:false,format:'esm',platform:'neutral'});
const {default:worker} = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].contents).toString('base64')}`);
const NativeDate = Date;
let clock = new NativeDate('2026-10-16T12:00:00Z').getTime();
globalThis.Date = class extends NativeDate { constructor(...args) { super(...(args.length ? args : [clock])); } static now() { return clock; } };
const entries = new Map();
globalThis.caches = {default: {async match(key) {return entries.get(key.url)?.clone();}, async put(key,response) {entries.set(key.url,response);}}};
let pending=[];
const ctx={waitUntil(promise){pending.push(promise);}};
async function call(query='',method='GET',path='/') {const r=await worker.fetch(new Request(`https://example.com${path}${query}`,{method}),{},ctx);await Promise.all(pending);pending=[];return r;}
assert.equal((await call()).status,302);
assert.equal((await call('?junk=x')).status,302);
assert.equal((await call('?dob=bad')).status,400);
assert.equal((await call('?dob=1990-01-01','POST')).status,405);
assert.equal((await call('?years=999999')).status,400);
assert.equal((await call('','GET','/wp-admin')).status,404);
assert.match(await (await call('','GET','/robots.txt')).text(),/Disallow: \//);
assert.equal((await call('?dob=1990-01-01','HEAD')).status,200);
assert.equal(entries.size,0);
const first = await call('?dob=1990-01-01');
assert.equal(first.headers.get('X-Calendar-Cache'),'MISS');
const bytes = await first.arrayBuffer();
assert.equal(new DataView(bytes).getUint32(16),1320);
assert.equal(new DataView(bytes).getUint32(20),2868);
assert.equal((await call('?dob=1990-01-01&junk=xyz')).headers.get('X-Calendar-Cache'),'HIT');
const shared = await call('?dob=1990-01-02');
assert.equal(shared.headers.get('X-Calendar-Cache'),'HIT');
assert.match(shared.headers.get('Content-Disposition'),/1990-01-02/);
clock += 86400000;
assert.equal((await call('?dob=1990-01-01')).headers.get('X-Calendar-Cache'),'HIT');
clock += 7 * 86400000;
assert.equal((await call('?dob=1990-01-01')).headers.get('X-Calendar-Cache'),'MISS');
clock = new NativeDate('2026-10-16T23:59:59Z').getTime();
const boundary = await call('?dob=2026-10-10');
assert.equal(boundary.headers.get('Cache-Control'),'public, max-age=1');
clock += 2000;
assert.equal((await call('?dob=2026-10-10')).headers.get('X-Calendar-Cache'),'MISS');
globalThis.Date = NativeDate;
console.log('Worker routing, PNG dimensions, normalized cache, filename sharing, HEAD, cross-day reuse, and week-boundary checks passed.');

